testthat::test_that("W08 timeout recovery is bounded and checkpoint safe", {
  p<-testthat::test_path("..","..","R","w08-cases.R")
  testthat::expect_silent(parse(file=p))
  src<-paste(readLines(p,warn=FALSE),collapse="\n")
  testthat::expect_match(src,"for(network_attempt in seq_len(3L))",fixed=TRUE)
  testthat::expect_match(src,"transport_errors.jsonl",fixed=TRUE)
  testthat::expect_match(src,"remote_completion_unknown=TRUE",fixed=TRUE)
  testthat::expect_match(src,"if(!retryable || network_attempt==3L)",fixed=TRUE)
  testthat::expect_match(src,"saved checkpoint preserved",fixed=TRUE)
  testthat::expect_match(src,"Sys.sleep(c(5,15)[[network_attempt]])",fixed=TRUE)
  testthat::expect_match(src,"for(record_id in selected[!selected %in% done_ids])",fixed=TRUE)
  testthat::expect_match(src,"validation_attempt=attempt",fixed=TRUE)
  testthat::expect_match(src,"model=model",fixed=TRUE)
  testthat::expect_match(src,"resp<-httr2::resp_body_json(response,simplifyVector=FALSE)",fixed=TRUE)
})
