testthat::test_that("Ostara offline atlas has coordinate fallback and no OSM tile requests", {
  template <- system.file("atlas","ostara_atlas_template.html",package="evidencelandscaper")
  coords <- system.file("extdata","ostara_w09_geocoding_draft.csv",package="evidencelandscaper")
  testthat::expect_true(file.exists(template))
  testthat::expect_true(file.exists(coords))
  html <- paste(readLines(template,warn=FALSE,encoding="UTF-8"),collapse="\n")
  testthat::expect_true(grepl('id="world"',html,fixed=TRUE))
  testthat::expect_true(grepl('id="markers"',html,fixed=TRUE))
  testthat::expect_true(grepl('.land{fill:none',html,fixed=TRUE))
  testthat::expect_false(grepl("tile.openstreetmap.org",html,fixed=TRUE))
  testthat::expect_true(grepl("tiles.openfreemap.org/styles/positron",html,fixed=TRUE))
  loc <- utils::read.csv(coords,stringsAsFactors=FALSE)
  testthat::expect_equal(nrow(loc),31L)
  testthat::expect_false(anyDuplicated(loc$observation_id)>0)
  testthat::expect_true(all(is.finite(loc$latitude)&is.finite(loc$longitude)))
  testthat::expect_true(all(abs(loc$latitude)<=90&abs(loc$longitude)<=180))
  testthat::expect_true(all(grepl("unverified",loc$coordinate_source,fixed=TRUE)))
})
