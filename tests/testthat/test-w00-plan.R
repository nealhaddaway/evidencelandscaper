test_that("W00 full planning is local and creates immutable query archive", {
  skip_if_not_installed("jsonlite")
  skip_if_not_installed("digest")
  root <- tempfile("evidence-root")
  dir.create(root)
  map <- create_map("planning_test", root)
  strategy <- system.file("w00", "example-strategy.json", package = "evidencelandscaper")
  result <- plan_w00(map, strategy, sources = "lens", mode = "full")
  expect_true(file.exists(result$search_plan))
  expect_true(file.exists(file.path(result$query_archive, "manifest.json")))
  expect_true(file.exists(file.path(map, "data", "workflow00", "source_selection.json")))
  plan <- jsonlite::fromJSON(result$search_plan, simplifyVector = FALSE)
  expect_identical(names(plan$source_queries), "lens")
  expect_error(plan_w00(map, strategy, sources = "not_a_source"), "failed")
})
