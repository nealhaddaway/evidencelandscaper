testthat::test_that("partial human imports override LLM and accumulate safely", {
  td<-tempfile("w04-human-")
  dir.create(td)
  dir.create(file.path(td,"consensus"))
  mk<-function(id,decision)list(record_id=id,
    screening=list(decision=decision,
      screening_input_sha256=paste0("input-",id),
      prompt_sha256="prompt-hash",
      requires_human_review=identical(decision,"uncertain")))
  original<-list(mk("work-a","retain"),mk("work-b","uncertain"),
                 mk("work-c","exclude"))
  tojl<-function(z,p)writeLines(vapply(z,function(x)
    jsonlite::toJSON(x,auto_unbox=TRUE,null="null"),character(1)),
    p,useBytes=TRUE)
  sha<-function(p)digest::digest(file=p,algo="sha256",serialize=FALSE)
  original_file<-file.path(td,"consensus","workflow04_consensus_layer.jsonl")
  tojl(original,original_file)
  jsonlite::write_json(list(run_type="trial",consensus_sha256=sha(original_file)),
    file.path(td,"local_manifest.json"),auto_unbox=TRUE)
  q<-lapply(original,function(z)list(
    review_case_id=paste0("w04-",z$record_id),
    record_id=z$record_id,
    model=z$screening))
  qfile<-file.path(td,"validation_queue.jsonl")
  tojl(q,qfile)
  mk_event<-function(id,decision)list(
    schema="local-w04-review-decision-v1",
    review_case_id=paste0("w04-",id),record_id=id,
    queue_sha256=sha(qfile),
    reviewer="Independent reviewer",decision=decision,reason="",
    record_input_sha256=paste0("input-",id),
    model_prompt_sha256="prompt-hash",
    created_at_utc="2026-11-02T09:00:00Z")
  one<-file.path(td,"human_one.jsonl")
  tojl(list(mk_event("work-a","exclude")),one)
  a<-evidencelandscaper::import_w04_authoritative_decisions(
    td,one)
  first<-jsonlite::fromJSON(file.path(a,"summary.json"))
  testthat::expect_equal(first$reviewed_records,1)
  testthat::expect_equal(first$uncertain,1)
  testthat::expect_identical(first$status,"partial")
  testthat::expect_false(evidencelandscaper:::.w04_latest_authoritative(td)$complete)
  testthat::expect_identical(
    evidencelandscaper::import_w04_authoritative_decisions(td,one),a)
  two<-file.path(td,"human_two.jsonl")
  tojl(list(mk_event("work-b","retain"),
            mk_event("work-c","retain")),two)
  b<-evidencelandscaper::import_w04_authoritative_decisions(td,two)
  second<-jsonlite::fromJSON(file.path(b,"summary.json"))
  testthat::expect_equal(second$reviewed_records,3)
  testthat::expect_equal(second$uncertain,0)
  testthat::expect_equal(second$retain,2)
  testthat::expect_equal(second$exclude,1)
  testthat::expect_identical(second$status,"final")
  testthat::expect_true(evidencelandscaper:::.w04_latest_authoritative(td)$complete)
  old<-jsonlite::fromJSON(file.path(a,"summary.json"))
  testthat::expect_identical(old$status,"partial")
  orig2<-lapply(readLines(original_file),
    jsonlite::fromJSON,simplifyVector=FALSE)
  testthat::expect_identical(orig2[[1]]$screening$decision,"retain")
  eff<-lapply(readLines(file.path(b,
    "workflow04_effective_screening_layer.jsonl")),
    jsonlite::fromJSON,simplifyVector=FALSE)
  testthat::expect_identical(eff[[1]]$screening$decision,"exclude")
  testthat::expect_identical(eff[[1]]$screening$decision_origin,"human_authoritative")
  testthat::expect_identical(eff[[2]]$screening$decision,"retain")
  testthat::expect_identical(eff[[3]]$screening$decision,"retain")
})

testthat::test_that("authoritative decisions require exact immutable queue", {
  td<-tempfile("w04-human-")
  dir.create(td)
  dir.create(file.path(td,"consensus"))
  original<-list(list(record_id="work-a",
    screening=list(decision="retain",screening_input_sha256="hash-a",
                   prompt_sha256="prompt")))
  p<-file.path(td,"consensus","workflow04_consensus_layer.jsonl")
  writeLines(jsonlite::toJSON(original[[1]],auto_unbox=TRUE),p)
  sha<-function(p)digest::digest(file=p,algo="sha256",serialize=FALSE)
  jsonlite::write_json(list(consensus_sha256=sha(p),run_type="trial"),
     file.path(td,"local_manifest.json"),auto_unbox=TRUE)
  q<-file.path(td,"validation_queue.jsonl")
  writeLines(jsonlite::toJSON(list(review_case_id="w04-work-a",
    record_id="work-a",model=original[[1]]$screening),auto_unbox=TRUE),q)
  d<-file.path(td,"decisions.jsonl")
  writeLines(jsonlite::toJSON(list(schema="local-w04-review-decision-v1",
    review_case_id="w04-work-a",record_id="work-a",
    queue_sha256=paste(rep("0",64),collapse=""),
    reviewer="Diana",decision="exclude",reason="",
    record_input_sha256="hash-a",model_prompt_sha256="prompt",
    created_at_utc="2026-11-02T09:00:00Z"),auto_unbox=TRUE),d)
  testthat::expect_error(
    evidencelandscaper::import_w04_authoritative_decisions(
      w04=td,decisions_file=d,queue_file=q),"queue hash")
})
