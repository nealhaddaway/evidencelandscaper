testthat::test_that("grey W09 repairs remain narrowly scoped and auditable", {
  source_path <- testthat::test_path("..", "..", "R", "w09-csv-case-extraction.R")
  testthat::expect_silent(parse(file=source_path))
  src <- paste(readLines(source_path, warn=FALSE), collapse="\n")
  testthat::expect_match(src, 'repair_grey_response<-function(candidate)', fixed=TRUE)
  testthat::expect_match(src, 'original="shared risk"', fixed=TRUE)
  testthat::expect_match(src, 'normalized="shared risks"', fixed=TRUE)
  testthat::expect_match(src, 'identical(old_status,"not_reported")', fixed=TRUE)
  testthat::expect_match(src, 'is_grey_schema&&identical(old_status,"not_reported")', fixed=TRUE)
  testthat::expect_match(src, 'repair="reporting_status_with_evidence"', fixed=TRUE)
  testthat::expect_match(src, 'deterministic_repairs=best$repairs', fixed=TRUE)
  testthat::expect_match(src, 'deterministic_repairs=repairs', fixed=TRUE)
  testthat::expect_match(src, 'if(revalidate_only)', fixed=TRUE)
  testthat::expect_match(src, 'if(length(candidates))', fixed=TRUE)
})
