testthat::test_that("first-run random samples are reproducible and leave full population unchanged", {
 ids <- sprintf("work-%03d",seq_len(100))
 a <- sample_evidence_records(ids,list(mode="n",n=15,uncertain="exclude"),seed=123L)
 b <- sample_evidence_records(rev(ids),list(mode="n",n=15,uncertain="exclude"),seed=123L)
 testthat::expect_identical(a$record_ids,b$record_ids)
 testthat::expect_length(a$record_ids,15L)
 testthat::expect_identical(a$population,100L)
 testthat::expect_identical(ids,sprintf("work-%03d",seq_len(100)))
 p <- sample_evidence_records(ids,list(mode="percent",percent=20,uncertain="exclude"),seed=1L)
 testthat::expect_length(p$record_ids,20L)
 testthat::expect_error(sample_evidence_records(c("a","a"),list(mode="all",uncertain="exclude")), "unique")
})
